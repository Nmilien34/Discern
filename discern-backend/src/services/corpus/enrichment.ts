// Generating the document side of the retrieval bridge.
//
// THE PROBLEM THIS SOLVES is query-document asymmetry, measured rather than
// assumed: on the 15 gate queries the corpus was embedded as bare ancient prose
// and the queries arrive as modern first-person sentences. Ephesians 2:8-10 —
// "not of yourselves… not of works" — sat at vector rank 6 for "faith is
// something I have to build myself", behind Hebrews 11, because nothing in its
// text resembles that sentence. Enrichment writes the missing half of the
// bridge: what this passage is about, and what somebody who needs it might
// actually be saying.
//
// Generated by a model, deliberately NOT curated by hand. A curated
// situation-to-passage lookup is a Phase 5 product feature and would contaminate
// this measurement — it would be answering the gate queries directly rather than
// improving retrieval.

